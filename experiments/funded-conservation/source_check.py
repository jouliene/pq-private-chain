"""Check the published ordinary C registration, staged node source and native generator inputs."""
import argparse
from hashlib import sha256
import importlib.util
import json
import os
from pathlib import Path
import shutil
import struct
import sys
import subprocess
import tarfile
import tempfile


HERE = Path(__file__).resolve().parent
EXPS = HERE.parent
FM = EXPS / "funded-membership"
BUILD = json.loads((FM / "registry/BUILD.json").read_bytes())["managed"]
NATIVE = "881128195a079fab2f97c0a32c02fdf390b08fe0f168b77d6f5f739a5e523ef6"
ARCHIVE = (EXPS / "funded-pq-assurance/C_DEPLOYMENT.sha256").read_text().split()[0]


def must(ok, message):
    if not ok:
        raise ValueError(message)


def hash_bytes(data):
    return sha256(data).hexdigest()


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generate(upstream, target):
    """Use the release generator callback, stopping before it invokes Cargo."""
    mng = load(EXPS / "managed-assets/native/build.py", "managed_builder")
    c = load(FM / "build_c.py", "membership_builder")

    class Generated(Exception):
        pass

    def capture(dest):
        # The generator invokes patch(1), which writes progress directly to fd 1.
        # Keep the report on stdout parseable and send progress to stderr.
        sys.stdout.flush()
        saved_stdout = os.dup(1)
        try:
            os.dup2(2, 1)
            c.configure(dest, "managed")
        finally:
            os.dup2(saved_stdout, 1)
            os.close(saved_stdout)
        tree = dest.parents[3]
        for path, expected in BUILD["generated_sources"].items():
            source = tree / path
            must(hash_bytes(source.read_bytes()) == expected, "wrong generated bytes for " + path)
            (target / path).parent.mkdir(exist_ok=True, parents=True)
            shutil.copyfile(source, target / path)
        for path in ("crates/qnero-note-core/src/note.rs", "crates/qnero-circuit/src/chain.rs",
                     "crates/qnero-circuit/src/layout.rs", "crates/qnero-circuit/src/header.rs",
                     "crates/qnero-circuit/src/note_gadget.rs", "crates/qnero-circuit/src/lib.rs",
                     "Cargo.lock"):
            (target / path).parent.mkdir(exist_ok=True, parents=True)
            shutil.copyfile(tree / path, target / path)
        raise Generated

    must(hash_bytes((FM / "hardening.patch").read_bytes()) == BUILD["hardening_patch_sha256"], "C hardening patch")
    os.environ["GIT_OPTIONAL_LOCKS"] = "0"
    with tempfile.TemporaryDirectory() as work:
        try:
            mng.prepare(Path(work), upstream.resolve(), None, capture)
        except Generated:
            return
    raise ValueError("source-capture hook was skipped")


def check(archive, upstream, target):
    must(hash_bytes(archive.read_bytes()) == ARCHIVE, "wrong published C deployment")
    key = (FM / "registry/managed.vk").read_bytes()
    must(hash_bytes(key) == BUILD["registration_sha256"] and len(key) == 1481, "registration")
    if upstream:
        generate(upstream, target)
    with tarfile.open(archive) as bundle:
        def read(path):
            member = bundle.getmember("deployment/" + path)
            must(member.isfile(), "expected regular file " + path)
            return bundle.extractfile(member).read()

        for path in ("c-keys/managed.vk", "devnet/c-managed.vk"):
            must(read(path) == key, path)
        binary = read("c-runtime/native")
        must(hash_bytes(binary) == NATIVE == read("devnet/approved-c-native.sha256").decode().strip(), "release native")
        reward = read("runtime/native")
        reward_sha = hash_bytes(reward)
        must(reward_sha == read("devnet/approved-native.sha256").decode().strip(), "reward role")
        for staged, repo in (("consensus", FM / "consensus.py"), ("managed_ops", FM / "ops_c.py")):
            must(read("devnet/" + staged + ".py") == repo.read_bytes(), "staged " + staged)
        # A/B staging changes the RPC supply observer, below the admission code.
        separator = b"    def supply_observation("
        staged, stop, _ = read("devnet/managed_ledger.py").partition(separator)
        base, begin, _ = (EXPS / "managed-assets/managed_ledger.py").read_bytes().partition(separator)
        must(stop == begin == separator and staged == base, "managed admission and registry")
        # Preserve the exact composed files, including earlier Python staging edits.
        for name in ("devnet/chain.py", "devnet/consensus.py", "devnet/swap_ledger.py",
                     "devnet/managed_ledger.py", "devnet/managed_ops.py", "devnet/managed_ops_c.py",
                     "devnet/runtime.py", "experiments/advancing-payments/run.py",
                     "experiments/advancing-payments/wire.py", "experiments/advancing-payments/state.py"):
            path = target / name
            path.parent.mkdir(exist_ok=True, parents=True)
            path.write_bytes(read(name))
        with tempfile.TemporaryDirectory() as tmp:
            native = Path(tmp) / "native"
            native.write_bytes(binary)
            native.chmod(0o700)
            result = subprocess.run([native, "register", Path(tmp) / "registered"], check=True,
                                    capture_output=True, env=dict(os.environ, RAYON_NUM_THREADS="2"))
            must(json.loads(result.stdout) == BUILD["registration"], "native registration metadata")
            must((Path(tmp) / "registered/managed.vk").read_bytes() == key, "re-registered verifier bytes")
            # The live node uses the separately approved, earlier hash role for rewards.
            # Compare all five ordinary-only fee totals to the independent funded oracle.
            reference = load(FM / "reference.py", "reward_reference")
            shared = Path(tmp) / "hash-role"
            shared.write_bytes(reward)
            shared.chmod(0o700)
            query, expected = bytearray(), bytearray()
            context, pk = bytes(range(32)), struct.pack("<4Q", 1, 2, 3, 4)
            for count in range(5):
                amount = 100 + 3 * count
                request = b"C" + context + pk + struct.pack("<QQ", amount, 0)
                query += struct.pack("<I", len(request)) + request
                expected += struct.pack("<I", 32) + reference.reward(context, pk, amount).commitment
            query += struct.pack("<I", 0)
            hashes = subprocess.run([shared, "hash"], input=query, capture_output=True, check=True)
            must(hashes.stdout == expected, "native ordinary block reward opening")
    print(json.dumps(dict(native_sha256=NATIVE, reward_role_sha256=reward_sha,
                          registered_key_sha256=hash_bytes(key), registration=BUILD["registration"],
                          reward_vectors=5,
                          regenerated_source_pins=len(BUILD["generated_sources"]) if upstream else 0),
                     sort_keys=True))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    parser.add_argument("--upstream", type=Path, help="pristine pinned Qnero checkout")
    parser.add_argument("--sources", type=Path, help="new directory to keep cited generated and deployed sources")
    args = parser.parse_args()
    if args.sources:
        args.sources.mkdir()
        check(args.archive, args.upstream, args.sources)
    else:
        with tempfile.TemporaryDirectory() as tmp:
            check(args.archive, args.upstream, Path(tmp))


if __name__ == "__main__":
    main()
